#!/usr/bin/env node
/**
 * Regenerate Supabase TypeScript types into @reviewnatin/shared.
 * Requires: supabase link (or SUPABASE_ACCESS_TOKEN for CI).
 *
 * Usage: npm run db:gen-types
 */
import { execSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const out = join(root, 'packages/shared/src/database.types.ts');

const raw = execSync('supabase gen types typescript --linked 2>/dev/null', {
  cwd: root,
  encoding: 'utf8',
});

const types = raw
  .split('\n')
  .filter((line) => !line.startsWith('Initialising login role'))
  .join('\n')
  .trim();

writeFileSync(
  out,
  `/** Generated by \`npm run db:gen-types\` — do not edit manually. */\n\n${types.trim()}\n`
);

console.log(`Wrote ${out}`);
